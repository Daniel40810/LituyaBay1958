-- Befunde mit ihren Quellen (4326)
CREATE OR REPLACE VIEW LB_V_BEFUND AS
SELECT b.BEFUND_ID, b.SCHLUESSEL, b.THEMA, b.AUSSAGE, b.WERT, b.EINHEIT, b.ART, b.ABSCHNITT, b.ORT_NAME, b.ZEIT_S, b.GILT, b.HERKUNFT, b.PHASE,
       (SELECT LISTAGG(q.KURZ || NVL2(bq.SEITE, ' S. ' || bq.SEITE, ''), ', ') WITHIN GROUP (ORDER BY q.KURZ)
          FROM LB_BEFUND_QUELLE bq JOIN LB_QUELLE q ON q.QUELLE_ID = bq.QUELLE_ID WHERE bq.BEFUND_ID = b.BEFUND_ID) AS QUELLEN,
       CASE WHEN b.ORT IS NOT NULL THEN SDO_CS.TRANSFORM(b.ORT, 4326) END AS ORT_4326
  FROM LB_BEFUND b
/
-- Befunde je Art (wie viel ist belegt, wie viel gesetzt)
CREATE OR REPLACE VIEW LB_V_BEFUND_ART AS
SELECT THEMA, ART, COUNT(*) AS ANZAHL FROM LB_BEFUND GROUP BY THEMA, ART
/
CREATE OR REPLACE VIEW LB_V_ZEUGE AS
SELECT z.ZEUGE_ID, z.NAME, z.ROLLE, z.BOOT, z.ZEIT_VON_S, z.ZEIT_BIS_S, z.ORT_NAME, z.AUSSAGE, z.ART, q.KURZ AS QUELLE, z.SEITE,
       CASE WHEN z.ORT IS NOT NULL THEN SDO_CS.TRANSFORM(z.ORT, 4326) END AS ORT_4326
  FROM LB_ZEUGE z LEFT JOIN LB_QUELLE q ON q.QUELLE_ID = z.QUELLE_ID
/
CREATE OR REPLACE VIEW LB_V_BOOT_BAHN AS
SELECT b.NAME AS BOOT, l.NAME AS LAUF, h.VON_S, h.BIS_S, h.LAENGE_M, h.HUB_M, h.ENDE, SDO_CS.TRANSFORM(SDO_CS.MAKE_2D(h.BAHN), 4326) AS BAHN_4326, h.BAHN
  FROM LB_BOOT_BAHN h JOIN LB_BOOT b ON b.BOOT_ID = h.BOOT_ID JOIN LB_EREIGNIS_LAUF l ON l.LAUF_ID = h.LAUF_ID
/
CREATE OR REPLACE VIEW LB_V_SCHNAPPSCHUSS AS
SELECT s.BILD_ID, s.ART, s.DATEI, s.AUFGENOMMEN, s.WELTZEIT, s.ZEIT_S, s.ZEITSTAND, s.HOEHE_M, s.RICHTUNG, s.NEIGUNG, z.NAME AS REGIEBUCH, s.SITZUNG_ID,
       s.BREITE, s.HOEHE, s.BYTES, s.BILDRATE, s.NOTIZ, CASE WHEN s.KAMERA IS NOT NULL THEN SDO_CS.TRANSFORM(s.KAMERA, 4326) END AS KAMERA_4326
  FROM LB_SCHNAPPSCHUSS s LEFT JOIN LB_SZENARIO z ON z.SZENARIO_ID = s.SZENARIO_ID
/
-- Kennzahlen der Läufe nebeneinander, mit dem Beleg zum Vergleich
CREATE OR REPLACE VIEW LB_V_LAUF_VERGLEICH AS
SELECT l.NAME, l.ART, l.QUELLE, l.ORT, ROUND(l.VOLUMEN_M3 / 1e6, 1) AS VOLUMEN_MIO_M3, l.PEGEL_M,
       ROUND(l.AUFLAUF_SPORN_M, 1) AS AUFLAUF_SPORN_M, (SELECT WERT FROM LB_BEFUND WHERE SCHLUESSEL = 'AUFLAUF_SPORN') AS SPORN_BELEGT_M,
       ROUND(l.AUFLAUF_MAX_M, 1) AS AUFLAUF_MAX_M, ROUND(l.ANKUNFT_CENOTAPH_S) AS CENOTAPH_S, ROUND(l.ANKUNFT_ANCHORAGE_S) AS ANCHORAGE_S,
       ROUND(l.ANKUNFT_EINGANG_S) AS EINGANG_S, l.ENERGIEANTEIL, l.DAUER_S, l.ERSTELLT
  FROM LB_EREIGNIS_LAUF l
/
CREATE OR REPLACE VIEW LB_V_SITZUNG AS
SELECT s.SITZUNG_ID, s.NAME, s.GESPEICHERT, s.RECHNER, s.HOEHE_M, s.RICHTUNG, s.NEIGUNG, s.MODUS, s.ZEITSTAND, s.RAFFER, l.NAME AS LAUF, z.NAME AS REGIEBUCH,
       CASE WHEN s.KAMERA IS NOT NULL THEN SDO_CS.TRANSFORM(s.KAMERA, 4326) END AS KAMERA_4326
  FROM LB_SITZUNG s LEFT JOIN LB_EREIGNIS_LAUF l ON l.LAUF_ID = s.LAUF_ID LEFT JOIN LB_SZENARIO z ON z.SZENARIO_ID = s.SZENARIO_ID
/
