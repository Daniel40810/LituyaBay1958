-- Raumindizes (nur, wo es sie noch nicht gibt)
DECLARE
    PROCEDURE ix(n VARCHAR2, t VARCHAR2, c VARCHAR2, d NUMBER) IS
        k NUMBER;
    BEGIN
        SELECT COUNT(*) INTO k FROM USER_INDEXES WHERE INDEX_NAME = n;
        IF k = 0 THEN
            EXECUTE IMMEDIATE 'CREATE INDEX ' || n || ' ON ' || t || ' (' || c || ') INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2 PARAMETERS (''sdo_indx_dims=' || d || ''')';
        END IF;
    END;
BEGIN
    ix('LB_BEFUND_SX', 'LB_BEFUND', 'ORT', 2);
    ix('LB_ZEUGE_SX', 'LB_ZEUGE', 'ORT', 2);
    ix('LB_BOOT_SX', 'LB_BOOT', 'ANKERPLATZ', 2);
    ix('LB_BOOT_BAHN_SX', 'LB_BOOT_BAHN', 'BAHN', 2);
    ix('LB_KAMERA_FAHRT_SX', 'LB_KAMERA_FAHRT', 'BAHN', 2);
    ix('LB_SCHNAPPSCHUSS_SX', 'LB_SCHNAPPSCHUSS', 'KAMERA', 2);
    ix('LB_SITZUNG_SX', 'LB_SITZUNG', 'KAMERA', 2);
END;
