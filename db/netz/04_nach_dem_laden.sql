-- UFER: eine logische Partition (85 Knoten), BLOBs
DECLARE
    weg VARCHAR2(4000);
BEGIN
    BEGIN
        SDO_NET.LOGICAL_PARTITION('LB_NET_UFER', 'LB_NET_UFER_PART$', 5000, 'DATA_PUMP_DIR', 'lb_netz.log', 'a', 1);
        weg := 'LOGICAL_PARTITION ja';
    EXCEPTION WHEN OTHERS THEN
        weg := 'LOGICAL_PARTITION nein: ' || SQLERRM || '; von Hand';
        BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_UFER_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
        EXECUTE IMMEDIATE 'CREATE TABLE LB_NET_UFER_PART$ (NODE_ID NUMBER PRIMARY KEY, PARTITION_ID NUMBER, LINK_LEVEL NUMBER)';
        EXECUTE IMMEDIATE 'INSERT INTO LB_NET_UFER_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL) SELECT NODE_ID, 1, 1 FROM LB_NET_UFER_NODE$';
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_UFER_PART$' WHERE NETWORK = 'LB_NET_UFER';
    COMMIT;
    SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_UFER', 1, 'LB_NET_UFER_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_UFER_PBLOB$') WHERE NETWORK = 'LB_NET_UFER';
    COMMIT;
    LB_PROBE_SETZEN(25, 'Partition LB_NET_UFER', 'LOGICAL_PARTITION, GENERATE_PARTITION_BLOBS (LRS)', weg || '; BLOBs erzeugt', CASE WHEN weg = 'LOGICAL_PARTITION ja' THEN 'J' ELSE 'N' END);
EXCEPTION WHEN OTHERS THEN
    LB_PROBE_SETZEN(25, 'Partition LB_NET_UFER', 'LOGICAL_PARTITION, GENERATE_PARTITION_BLOBS (LRS)', NVL(weg, '') || ' ' || SQLERRM, 'N');
END;
