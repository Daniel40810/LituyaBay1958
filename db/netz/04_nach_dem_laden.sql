-- WELLE: räumlich partitionieren (5 000 Knoten je Partition, Werkbuch 7.1), sonst logisch; BLOBs mit Benutzerdaten (die vier Kosten)
DECLARE
    weg VARCHAR2(4000);
    n NUMBER;
    PROCEDURE weg_damit IS
    BEGIN
        EXECUTE IMMEDIATE 'DROP TABLE LB_NET_WELLE_PART$ PURGE';
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
BEGIN
    BEGIN
        SDO_NET.SPATIAL_PARTITION('LB_NET_WELLE', 'LB_NET_WELLE_PART$', 5000, 'DATA_PUMP_DIR', 'lb_netz.log', 'a', 1);
        weg := 'SPATIAL_PARTITION (5000) ja';
    EXCEPTION WHEN OTHERS THEN
        weg := 'SPATIAL_PARTITION (5000) nein: ' || SQLERRM;
        weg_damit;
        SDO_NET.LOGICAL_PARTITION('LB_NET_WELLE', 'LB_NET_WELLE_PART$', 5000, 'DATA_PUMP_DIR', 'lb_netz.log', 'a', 1);
        weg := weg || '; LOGICAL_PARTITION (5000) ja';
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_WELLE_PART$' WHERE NETWORK = 'LB_NET_WELLE';
    COMMIT;
    BEGIN
        SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WELLE', 1, 'LB_NET_WELLE_PBLOB$', TRUE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
        weg := weg || '; BLOBs mit Benutzerdaten';
    EXCEPTION WHEN OTHERS THEN
        weg := weg || '; BLOBs mit Benutzerdaten nein: ' || SQLERRM || '; ohne';
        BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_WELLE_PBLOB$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
        SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WELLE', 1, 'LB_NET_WELLE_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_WELLE_PBLOB$') WHERE NETWORK = 'LB_NET_WELLE';
    COMMIT;
    EXECUTE IMMEDIATE 'SELECT COUNT(DISTINCT PARTITION_ID) FROM LB_NET_WELLE_PART$' INTO n;
    LB_PROBE_SETZEN(24, 'Partition LB_NET_WELLE', 'SPATIAL_PARTITION (5000), GENERATE_PARTITION_BLOBS mit Benutzerdaten',
                    weg || '; ' || n || ' Partitionen', CASE WHEN weg LIKE 'SPATIAL_PARTITION (5000) ja; BLOBs mit Benutzerdaten%' THEN 'J' ELSE 'N' END);
END;
