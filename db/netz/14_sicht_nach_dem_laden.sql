DECLARE
    PROCEDURE idx(s VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE s;
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1408, -955) THEN RAISE; END IF;
    END;
BEGIN
    idx('CREATE INDEX LB_NET_SICHT_LINK_S ON LB_NET_SICHT_LINK$ (START_NODE_ID)');
    idx('CREATE INDEX LB_NET_SICHT_LINK_E ON LB_NET_SICHT_LINK$ (END_NODE_ID)');
    idx('CREATE INDEX LB_NET_SICHT_NODE_SX ON LB_NET_SICHT_NODE$ (GEOMETRY) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_NET_SICHT_LINK_SX ON LB_NET_SICHT_LINK$ (GEOMETRY) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_SICHT_FAHRT_SX ON LB_SICHT_FAHRT (PUNKT) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
END;
/
DECLARE
    weg VARCHAR2(4000);
BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_SICHT_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
    EXECUTE IMMEDIATE 'CREATE TABLE LB_NET_SICHT_PART$ (NODE_ID NUMBER PRIMARY KEY, PARTITION_ID NUMBER, LINK_LEVEL NUMBER)';
    EXECUTE IMMEDIATE 'INSERT INTO LB_NET_SICHT_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL) SELECT NODE_ID, 1, 1 FROM LB_NET_SICHT_NODE$';
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_SICHT_PART$' WHERE NETWORK = 'LB_NET_SICHT';
    COMMIT;
    BEGIN
        SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_SICHT', 1, 'LB_NET_SICHT_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
        UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_SICHT_PBLOB$') WHERE NETWORK = 'LB_NET_SICHT';
        weg := 'eine Partition, BLOBs ja';
    EXCEPTION WHEN OTHERS THEN
        weg := 'eine Partition, BLOBs nein: ' || SQLERRM || ' bei ' || REPLACE(SUBSTR(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 200), CHR(10), ' ');
        UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NULL WHERE NETWORK = 'LB_NET_SICHT';
        BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_SICHT_PBLOB$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
    END;
    COMMIT;
    LB_PROBE_SETZEN(33, 'Partition LB_NET_SICHT (ungerichtet, 3D-Geometrie)', 'eine Partition von Hand, GENERATE_PARTITION_BLOBS', SUBSTR(weg, 1, 400),
                    CASE WHEN weg NOT LIKE '%nein%' THEN 'J' ELSE 'N' END);
END;
/
CREATE OR REPLACE VIEW LB_V_SICHT_KNOTEN AS
SELECT n.NODE_ID, n.NODE_NAME AS NAME, n.ART, n.MOTIV, ROUND(n.HOEHE, 1) AS HOEHE,
       (SELECT COUNT(*) FROM LB_NET_SICHT_LINK$ l WHERE l.START_NODE_ID = n.NODE_ID OR l.END_NODE_ID = n.NODE_ID) AS SICHTLINIEN,
       (SELECT ROUND(MAX(l.LAENGE) / 1000, 1) FROM LB_NET_SICHT_LINK$ l WHERE l.START_NODE_ID = n.NODE_ID OR l.END_NODE_ID = n.NODE_ID) AS WEITESTE_KM
  FROM LB_NET_SICHT_NODE$ n
/
CREATE OR REPLACE VIEW LB_V_SICHT_FAHRT AS
SELECT f.FAHRT, COUNT(*) AS PUNKTE, COUNT(f.MOTIV) AS MOTIVE, ROUND(MAX(f.ZEIT_S) / 60, 1) AS FLUGZEIT_MIN
  FROM LB_SICHT_FAHRT f
 GROUP BY f.FAHRT
/
