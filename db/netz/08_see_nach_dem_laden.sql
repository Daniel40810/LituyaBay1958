DECLARE
    PROCEDURE idx(s VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE s;
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1408, -955) THEN RAISE; END IF;
    END;
BEGIN
    idx('CREATE INDEX LB_NET_SEE_LINK_S ON LB_NET_SEE_LINK$ (START_NODE_ID)');
    idx('CREATE INDEX LB_NET_SEE_LINK_E ON LB_NET_SEE_LINK$ (END_NODE_ID)');
    idx('CREATE INDEX LB_NET_SEE_NODE_SX ON LB_NET_SEE_NODE$ (GEOMETRY) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_NET_SEE_LINK_SX ON LB_NET_SEE_LINK$ (GEOMETRY) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_FLUCHT_SX ON LB_FLUCHT (WEG) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
END;
/
DECLARE
    weg VARCHAR2(4000);
BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_SEE_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN
        SDO_NET.SPATIAL_PARTITION('LB_NET_SEE', 'LB_NET_SEE_PART$', 5000, 'DATA_PUMP_DIR', 'lb_netz.log', 'a', 1);
        weg := 'SPATIAL_PARTITION ja';
    EXCEPTION WHEN OTHERS THEN
        weg := 'SPATIAL_PARTITION nein: ' || SQLERRM || '; von Hand';
        BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_SEE_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
        EXECUTE IMMEDIATE 'CREATE TABLE LB_NET_SEE_PART$ (NODE_ID NUMBER PRIMARY KEY, PARTITION_ID NUMBER, LINK_LEVEL NUMBER)';
        EXECUTE IMMEDIATE 'INSERT INTO LB_NET_SEE_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL) SELECT NODE_ID, 1, 1 FROM LB_NET_SEE_NODE$';
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_SEE_PART$' WHERE NETWORK = 'LB_NET_SEE';
    COMMIT;
    SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_SEE', 1, 'LB_NET_SEE_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_SEE_PBLOB$') WHERE NETWORK = 'LB_NET_SEE';
    COMMIT;
    LB_PROBE_SETZEN(30, 'Partition LB_NET_SEE (gerichtet)', 'SPATIAL_PARTITION, GENERATE_PARTITION_BLOBS', weg, CASE WHEN weg = 'SPATIAL_PARTITION ja' THEN 'J' ELSE 'N' END);
END;
/
CREATE OR REPLACE VIEW LB_V_FLUCHT AS
SELECT BOOT, FRONT, ABFAHRT_S, ENTKOMMEN, ANKUNFT_S, RESERVE_S, SPAETESTE,
       CASE WHEN WEG IS NULL THEN NULL ELSE ROUND(SDO_GEOM.SDO_LENGTH(WEG, 0.005)) END AS WEG_M
  FROM LB_FLUCHT
/
