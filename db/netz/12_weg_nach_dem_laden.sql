-- Phase 16a: LAGE aus OST, NORD, HOEHE; Indizes; Partitionen in festen Kacheln
-- (Ebene 1: 700 m im Kern, rund 4 900 Knoten; Ebene 2: 3,5 km in der Szene,
-- ebenso), weil LOGICAL_PARTITION bei Millionen Knoten zu lange braucht.
-- Befund 16: in der Sicht der Ebene 1 liegen auch die Kanten der Ebene 2, also
-- stehen dort alle Knoten (Ebene-2-Knoten mit Kacheln ab 1001). BLOBs je Ebene.
-- ============================================================================
DECLARE
    PROCEDURE idx(s VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE s;
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1408, -955) THEN RAISE; END IF;
    END;
BEGIN
    EXECUTE IMMEDIATE 'UPDATE LB_NET_WEG_NODE$ SET LAGE = SDO_GEOMETRY(3001, 26908, SDO_POINT_TYPE(OST, NORD, HOEHE), NULL, NULL)';
    COMMIT;
    idx('CREATE INDEX LB_NET_WEG_LINK_S ON LB_NET_WEG_LINK$ (START_NODE_ID) NOLOGGING');
    idx('CREATE INDEX LB_NET_WEG_LINK_E ON LB_NET_WEG_LINK$ (END_NODE_ID) NOLOGGING');
    idx('CREATE INDEX LB_NET_WEG_NODE_P ON LB_NET_WEG_NODE$ (PARENT_NODE_ID) NOLOGGING');
    idx('CREATE INDEX LB_NET_WEG_NODE_SX ON LB_NET_WEG_NODE$ (LAGE) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_WEG_ROUTE_SX ON LB_WEG_ROUTE (PUNKT) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
END;
/
DECLARE
    weg VARCHAR2(4000);
    n1 NUMBER;
    n2 NUMBER;
BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_WEG_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
    EXECUTE IMMEDIATE 'CREATE TABLE LB_NET_WEG_PART$ (NODE_ID NUMBER, PARTITION_ID NUMBER, LINK_LEVEL NUMBER, CONSTRAINT LB_NET_WEG_PART_PK PRIMARY KEY (NODE_ID, LINK_LEVEL)) NOLOGGING';
    EXECUTE IMMEDIATE 'INSERT /*+ APPEND */ INTO LB_NET_WEG_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL)
        SELECT NODE_ID,
               CASE WHEN HIERARCHY_LEVEL = 1 THEN FLOOR((6512000 - NORD) / 700) * 35 + FLOOR((OST - 340000) / 700) + 1
                    ELSE 1000 + FLOOR((6540000 - NORD) / 3500) * 19 + FLOOR((OST - 322000) / 3500) + 1 END, 1
          FROM LB_NET_WEG_NODE$';
    COMMIT;
    EXECUTE IMMEDIATE 'INSERT /*+ APPEND */ INTO LB_NET_WEG_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL)
        SELECT NODE_ID, FLOOR((6540000 - NORD) / 3500) * 19 + FLOOR((OST - 322000) / 3500) + 1, 2
          FROM LB_NET_WEG_NODE$ WHERE HIERARCHY_LEVEL = 2';
    COMMIT;
    EXECUTE IMMEDIATE 'SELECT COUNT(DISTINCT PARTITION_ID) FROM LB_NET_WEG_PART$ WHERE LINK_LEVEL = 1' INTO n1;
    EXECUTE IMMEDIATE 'SELECT COUNT(DISTINCT PARTITION_ID) FROM LB_NET_WEG_PART$ WHERE LINK_LEVEL = 2' INTO n2;
    weg := 'Kacheln: Ebene 1 ' || n1 || ' Partitionen, Ebene 2 ' || n2;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_WEG_PART$' WHERE NETWORK = 'LB_NET_WEG';
    COMMIT;
    SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WEG', 1, 'LB_NET_WEG_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
    weg := weg || '; BLOBs Ebene 1 ja';
    BEGIN
        SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WEG', 2, 'LB_NET_WEG_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
        weg := weg || ', Ebene 2 ja';
    EXCEPTION WHEN OTHERS THEN
        weg := weg || ', Ebene 2 nein: ' || SQLERRM;
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_WEG_PBLOB$') WHERE NETWORK = 'LB_NET_WEG';
    COMMIT;
    LB_PROBE_SETZEN(32, 'Partition LB_NET_WEG (logisch, zwei Ebenen, Millionen Kanten)', 'Kacheln von Hand, GENERATE_PARTITION_BLOBS je Ebene', SUBSTR(weg, 1, 400),
                    CASE WHEN weg NOT LIKE '%nein%' THEN 'J' ELSE 'N' END);
END;
/
CREATE OR REPLACE VIEW LB_V_WEG_KLASSE AS
SELECT HIERARCHY_LEVEL AS EBENE, KLASSE, COUNT(*) AS KNOTEN,
       ROUND(COUNT(*) * CASE WHEN HIERARCHY_LEVEL = 1 THEN 100 ELSE 2500 END / 1e6, 3) AS FLAECHE_KM2
  FROM LB_NET_WEG_NODE$ GROUP BY HIERARCHY_LEVEL, KLASSE
