-- meldet (Befund 16a: Indizes, Kacheln und BLOBs zusammen 95 min).
-- Seit 16b: Kacheln 1 km im Kern und 5 km in der Szene (je rund 10 000 Knoten,
-- halb so viele Partitionen), Index auf LB_NET_WEG_PART$ (LINK_LEVEL,
-- PARTITION_ID, NODE_ID) und Statistiken vor GENERATE_PARTITION_BLOBS.
-- Befund 16: in der Sicht der Ebene 1 liegen auch die Kanten der Ebene 2, also
-- stehen dort alle Knoten (Ebene-2-Knoten mit Kacheln ab 1001).
