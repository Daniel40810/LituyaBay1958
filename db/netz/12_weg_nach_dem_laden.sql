BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_WEG_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
    EXECUTE IMMEDIATE 'CREATE TABLE LB_NET_WEG_PART$ (NODE_ID NUMBER, PARTITION_ID NUMBER, LINK_LEVEL NUMBER, CONSTRAINT LB_NET_WEG_PART_PK PRIMARY KEY (NODE_ID, LINK_LEVEL)) NOLOGGING';
END;
/
INSERT /*+ APPEND */ INTO LB_NET_WEG_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL)
SELECT NODE_ID,
       CASE WHEN HIERARCHY_LEVEL = 1 THEN FLOOR((6512000 - NORD) / 1000) * 24 + FLOOR((OST - 340000) / 1000) + 1
            ELSE 1000 + FLOOR((6540000 - NORD) / 5000) * 14 + FLOOR((OST - 322000) / 5000) + 1 END, 1
  FROM LB_NET_WEG_NODE$
/
COMMIT
/
INSERT /*+ APPEND */ INTO LB_NET_WEG_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL)
SELECT NODE_ID, FLOOR((6540000 - NORD) / 5000) * 14 + FLOOR((OST - 322000) / 5000) + 1, 2
  FROM LB_NET_WEG_NODE$ WHERE HIERARCHY_LEVEL = 2
/
COMMIT
/
CREATE INDEX LB_NET_WEG_PART_P ON LB_NET_WEG_PART$ (LINK_LEVEL, PARTITION_ID, NODE_ID) NOLOGGING
/
BEGIN
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_WEG_PART$' WHERE NETWORK = 'LB_NET_WEG';
    COMMIT;
    DBMS_STATS.GATHER_TABLE_STATS(USER, 'LB_NET_WEG_NODE$', cascade => TRUE, degree => 4);
    DBMS_STATS.GATHER_TABLE_STATS(USER, 'LB_NET_WEG_LINK$', cascade => TRUE, degree => 4);
    DBMS_STATS.GATHER_TABLE_STATS(USER, 'LB_NET_WEG_PART$', cascade => TRUE);
END;
/
BEGIN
    SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WEG', 1, 'LB_NET_WEG_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
END;
/
DECLARE
    weg VARCHAR2(4000);
    n1 NUMBER;
    n2 NUMBER;
BEGIN
    BEGIN
        SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WEG', 2, 'LB_NET_WEG_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
        weg := 'BLOBs Ebene 1 ja, Ebene 2 ja';
    EXCEPTION WHEN OTHERS THEN
        weg := 'BLOBs Ebene 1 ja, Ebene 2 nein: ' || SQLERRM;
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_WEG_PBLOB$') WHERE NETWORK = 'LB_NET_WEG';
    COMMIT;
    EXECUTE IMMEDIATE 'SELECT COUNT(DISTINCT PARTITION_ID) FROM LB_NET_WEG_PART$ WHERE LINK_LEVEL = 1' INTO n1;
    EXECUTE IMMEDIATE 'SELECT COUNT(DISTINCT PARTITION_ID) FROM LB_NET_WEG_PART$ WHERE LINK_LEVEL = 2' INTO n2;
    weg := 'Kacheln 1 km / 5 km: Ebene 1 ' || n1 || ' Partitionen, Ebene 2 ' || n2 || '; ' || weg;
    LB_PROBE_SETZEN(32, 'Partition LB_NET_WEG (logisch, zwei Ebenen, Millionen Kanten)', 'Kacheln von Hand, Statistik, GENERATE_PARTITION_BLOBS je Ebene', SUBSTR(weg, 1, 400),
                    CASE WHEN weg NOT LIKE '%nein%' THEN 'J' ELSE 'N' END);
END;
