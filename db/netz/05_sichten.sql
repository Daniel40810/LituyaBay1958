CREATE OR REPLACE VIEW LB_V_ANKUNFT AS
SELECT a.KOSTEN, a.NODE_ID, n.ART, a.T_LOD, a.T_ROUTE, a.T_LOD - a.T_ROUTE AS DIFF, n.TIEFE_HEUTE, n.GEOMETRY
  FROM LB_ANKUNFT a
  JOIN LB_NET_WELLE_NODE$ n ON n.NODE_ID = a.NODE_ID
/
CREATE OR REPLACE VIEW LB_V_ANKUNFT_VERGLEICH AS
SELECT KOSTEN, COUNT(*) AS KNOTEN, COUNT(T_LOD) AS MIT_LOD, MAX(ABS(T_LOD - T_ROUTE)) AS GROESSTE_ABWEICHUNG, MAX(T_LOD) AS LETZTE_ANKUNFT
  FROM LB_ANKUNFT
 GROUP BY KOSTEN
/
CREATE OR REPLACE VIEW LB_V_AUFLAUF AS
SELECT a.AUFLAUF_ID, u.NAME AS STRANG, a.M, a.HOEHE, a.JAHR, a.NAME, a.QUELLE, a.ART, a.GEOMETRY
  FROM LB_AUFLAUF a
  JOIN LB_UFER_GEOM u ON u.GEOM_ID = a.GEOM_ID
/
