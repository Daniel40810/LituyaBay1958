CREATE OR REPLACE VIEW LB_V_HERKUNFT AS
SELECT l.LINK_ID, l.ART,
       v.NODE_ID AS VON_ID, v.ART AS VON_ART, v.NODE_NAME AS VON,
       n.NODE_ID AS NACH_ID, n.ART AS NACH_ART, n.NODE_NAME AS NACH
  FROM LB_NET_HERKUNFT_LINK$ l
  JOIN LB_NET_HERKUNFT_NODE$ v ON v.NODE_ID = l.START_NODE_ID
  JOIN LB_NET_HERKUNFT_NODE$ n ON n.NODE_ID = l.END_NODE_ID
/
-- Quellen je Szenenobjekt, über alle Stufen (CONNECT BY als zweiter Weg neben traceIn)
CREATE OR REPLACE VIEW LB_V_HERKUNFT_QUELLEN AS
SELECT o.NODE_ID AS OBJEKT_ID, o.NODE_NAME AS OBJEKT, q.NODE_ID AS QUELLE_ID, q.NODE_NAME AS QUELLE
  FROM LB_NET_HERKUNFT_NODE$ o
  JOIN LB_NET_HERKUNFT_NODE$ q ON q.ART = 'QUELLE'
 WHERE o.ART = 'OBJEKT'
   AND EXISTS (SELECT 1 FROM LB_NET_HERKUNFT_LINK$ l
                WHERE l.START_NODE_ID = q.NODE_ID
                START WITH l.END_NODE_ID = o.NODE_ID
                CONNECT BY NOCYCLE PRIOR l.START_NODE_ID = l.END_NODE_ID)
/
CREATE OR REPLACE VIEW LB_V_NDM_PROBE AS
SELECT NR, FAEHIGKEIT, PRUEFUNG, CASE OK WHEN 'J' THEN 'ja' WHEN 'N' THEN 'nein' ELSE '-' END AS VORHANDEN, WEG, ERGEBNIS, GEPRUEFT
  FROM LB_NDM_PROBE
 ORDER BY NR, FAEHIGKEIT
/
