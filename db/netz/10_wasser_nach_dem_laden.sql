DECLARE
    PROCEDURE idx(s VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE s;
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1408, -955) THEN RAISE; END IF;
    END;
BEGIN
    idx('CREATE INDEX LB_NET_WASSER_LINK_S ON LB_NET_WASSER_LINK$ (START_NODE_ID)');
    idx('CREATE INDEX LB_NET_WASSER_LINK_E ON LB_NET_WASSER_LINK$ (END_NODE_ID)');
    idx('CREATE INDEX LB_NET_WASSER_NODE_P ON LB_NET_WASSER_NODE$ (PARENT_NODE_ID)');
    idx('CREATE INDEX LB_NET_WASSER_NODE_SX ON LB_NET_WASSER_NODE$ (GEOMETRY) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_NET_WASSER_LINK_SX ON LB_NET_WASSER_LINK$ (GEOMETRY) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_EINZUG_SX ON LB_EINZUG (UMRISS) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_SEE_SX ON LB_SEE (PUNKT) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
    idx('CREATE INDEX LB_SENKE_SX ON LB_SENKE (PUNKT) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2');
END;
/
DECLARE
    weg VARCHAR2(4000);
BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_WASSER_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN
        SDO_NET.SPATIAL_PARTITION('LB_NET_WASSER', 'LB_NET_WASSER_PART$', 5000, 'DATA_PUMP_DIR', 'lb_netz.log', 'a', 1);
        weg := 'SPATIAL_PARTITION (Ebene 1) ja';
    EXCEPTION WHEN OTHERS THEN
        weg := 'SPATIAL_PARTITION (Ebene 1) nein: ' || SQLERRM || '; von Hand';
        BEGIN EXECUTE IMMEDIATE 'DROP TABLE LB_NET_WASSER_PART$ PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
        EXECUTE IMMEDIATE 'CREATE TABLE LB_NET_WASSER_PART$ (NODE_ID NUMBER, PARTITION_ID NUMBER, LINK_LEVEL NUMBER)';
        EXECUTE IMMEDIATE 'INSERT INTO LB_NET_WASSER_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL) SELECT NODE_ID, 1, 1 FROM LB_NET_WASSER_NODE$ WHERE NVL(HIERARCHY_LEVEL, 1) = 1';
    END;
    -- Ebene 2 (einige hundert Knoten) als eine Partition
    BEGIN
        EXECUTE IMMEDIATE 'INSERT INTO LB_NET_WASSER_PART$ (NODE_ID, PARTITION_ID, LINK_LEVEL) SELECT NODE_ID, 1, 2 FROM LB_NET_WASSER_NODE$ WHERE HIERARCHY_LEVEL = 2';
        weg := weg || '; Ebene 2 eine Partition';
    EXCEPTION WHEN OTHERS THEN
        weg := weg || '; Ebene 2 nein: ' || SQLERRM;
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_TABLE_NAME = 'LB_NET_WASSER_PART$' WHERE NETWORK = 'LB_NET_WASSER';
    COMMIT;
    SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WASSER', 1, 'LB_NET_WASSER_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
    weg := weg || '; BLOBs Ebene 1 ja';
    BEGIN
        SDO_NET.GENERATE_PARTITION_BLOBS('LB_NET_WASSER', 2, 'LB_NET_WASSER_PBLOB$', FALSE, TRUE, 'DATA_PUMP_DIR', 'lb_netz.log', 'a');
        weg := weg || ', Ebene 2 ja';
    EXCEPTION WHEN OTHERS THEN
        weg := weg || ', Ebene 2 nein: ' || SQLERRM;
    END;
    UPDATE USER_SDO_NETWORK_METADATA SET PARTITION_BLOB_TABLE_NAME = NVL(PARTITION_BLOB_TABLE_NAME, 'LB_NET_WASSER_PBLOB$') WHERE NETWORK = 'LB_NET_WASSER';
    COMMIT;
    LB_PROBE_SETZEN(31, 'Partition LB_NET_WASSER (hierarchisch, zwei Ebenen)', 'SPATIAL_PARTITION Ebene 1, Ebene 2 von Hand, GENERATE_PARTITION_BLOBS je Ebene', SUBSTR(weg, 1, 400),
                    CASE WHEN weg LIKE 'SPATIAL_PARTITION (Ebene 1) ja%' AND weg NOT LIKE '%nein%' THEN 'J' ELSE 'N' END);
END;
/
CREATE OR REPLACE VIEW LB_V_EINZUG AS
SELECT e.NODE_ID, e.ART, e.NAME, e.ZIEL, e.FLAECHE_EIGEN_KM2, e.FLAECHE_KM2, e.EIS_ANTEIL,
       CASE WHEN e.UMRISS IS NULL THEN NULL ELSE ROUND(SDO_GEOM.SDO_AREA(e.UMRISS, 0.005) / 1e6, 4) END AS UMRISS_KM2
  FROM LB_EINZUG e
/
CREATE OR REPLACE VIEW LB_V_WASSER_ZIEL AS
SELECT z.NODE_NAME AS ZIEL,
       (SELECT ROUND(SUM(e.FLAECHE_EIGEN_KM2), 4) FROM LB_EINZUG e
         WHERE e.NODE_ID IN (SELECT l.START_NODE_ID FROM LB_NET_WASSER_LINK$ l
                              START WITH l.END_NODE_ID = z.NODE_ID AND l.LINK_LEVEL = 2
                              CONNECT BY PRIOR l.START_NODE_ID = l.END_NODE_ID AND l.LINK_LEVEL = 2)) AS FLAECHE_KM2,
       z.FLAECHE_KM2 AS FLAECHE_RASTER_KM2
  FROM LB_NET_WASSER_NODE$ z
 WHERE z.ART = 'ZIEL' AND z.HIERARCHY_LEVEL = 2
/
